import dns from "dns";

// -----------------------------------------------------------------------------
// MongoDB Atlas DNS fix
// -----------------------------------------------------------------------------

dns.setServers(["1.1.1.1"]);

import express from "express";
import cors from "cors";
import dotenv from "dotenv";
import helmet from "helmet";
import morgan from "morgan";

// -----------------------------------------------------------------------------
// Load environment variables
// -----------------------------------------------------------------------------

dotenv.config();

// -----------------------------------------------------------------------------
// Database
// -----------------------------------------------------------------------------

import connectDB from "./config/db.js";

// -----------------------------------------------------------------------------
// Routes
// -----------------------------------------------------------------------------

import authRoutes from "./routes/authRoutes.js";
import airlineRoutes from "./routes/airlineRoutes.js";
import airportRoutes from "./routes/airportRoutes.js";
import aircraftRoutes from "./routes/aircraftRoutes.js";
import flightRoutes from "./routes/flightRoutes.js";
import bookingRoutes from "./routes/bookingRoutes.js";
import paymentRoutes from "./routes/paymentRoutes.js";
import adminRoutes from "./routes/adminRoutes.js";

// -----------------------------------------------------------------------------
// Services
// -----------------------------------------------------------------------------

import { verifyEmailConnection } from "./services/emailService.js";
import { startBookingExpirationJob } from "./services/bookingExpirationService.js";

// -----------------------------------------------------------------------------
// Express App
// -----------------------------------------------------------------------------

const app = express();

// -----------------------------------------------------------------------------
// Environment
// -----------------------------------------------------------------------------

const PORT = process.env.PORT || 5000;

const CLIENT_URL =
  process.env.CLIENT_URL || "http://localhost:5173";

// -----------------------------------------------------------------------------
// CORS
// -----------------------------------------------------------------------------

app.use(
  cors({
    origin: CLIENT_URL,
    credentials: true,
    methods: [
      "GET",
      "POST",
      "PUT",
      "PATCH",
      "DELETE",
      "OPTIONS",
    ],
    allowedHeaders: [
      "Content-Type",
      "Authorization",
    ],
  })
);

// -----------------------------------------------------------------------------
// Security Middleware
// -----------------------------------------------------------------------------

app.use(helmet());

// -----------------------------------------------------------------------------
// Logging
// -----------------------------------------------------------------------------

app.use(morgan("dev"));

// -----------------------------------------------------------------------------
// Body Parsers
// -----------------------------------------------------------------------------

app.use(express.json());

app.use(
  express.urlencoded({
    extended: true,
  })
);

// -----------------------------------------------------------------------------
// Health Check
// -----------------------------------------------------------------------------

app.get("/api/health", (req, res) => {
  res.status(200).json({
    success: true,
    message: "Flight Booking API is running",
  });
});

// -----------------------------------------------------------------------------
// Root Route
// -----------------------------------------------------------------------------

app.get("/", (req, res) => {
  res.status(200).json({
    success: true,
    message: "Welcome to Flight Booking API",
  });
});

// -----------------------------------------------------------------------------
// Authentication Routes
// -----------------------------------------------------------------------------

app.use("/api/auth", authRoutes);

// -----------------------------------------------------------------------------
// Airline Routes
// -----------------------------------------------------------------------------

app.use("/api/airlines", airlineRoutes);

// -----------------------------------------------------------------------------
// Airport Routes
// -----------------------------------------------------------------------------

app.use("/api/airports", airportRoutes);

// -----------------------------------------------------------------------------
// Aircraft Routes
// -----------------------------------------------------------------------------

app.use("/api/aircraft", aircraftRoutes);

// -----------------------------------------------------------------------------
// Flight Routes
// -----------------------------------------------------------------------------

app.use("/api/flights", flightRoutes);

// -----------------------------------------------------------------------------
// Booking Routes
// -----------------------------------------------------------------------------

app.use("/api/bookings", bookingRoutes);

// -----------------------------------------------------------------------------
// Payment Routes
// -----------------------------------------------------------------------------

app.use("/api/payments", paymentRoutes);

// -----------------------------------------------------------------------------
// Admin Routes
// -----------------------------------------------------------------------------

app.use("/api/admin", adminRoutes);

// -----------------------------------------------------------------------------
// 404 Handler
// -----------------------------------------------------------------------------

app.use((req, res) => {
  res.status(404).json({
    success: false,
    message: `Route not found: ${req.method} ${req.originalUrl}`,
  });
});

// -----------------------------------------------------------------------------
// Global Error Handler
// -----------------------------------------------------------------------------

app.use((err, req, res, next) => {
  console.error("GLOBAL ERROR:", err);

  res.status(err.status || 500).json({
    success: false,
    message: err.message || "Internal server error",
  });
});

// -----------------------------------------------------------------------------
// Start Server
// -----------------------------------------------------------------------------

const startServer = async () => {
  try {
    // -------------------------------------------------------------------------
    // Connect MongoDB
    // -------------------------------------------------------------------------

    await connectDB();

    // -------------------------------------------------------------------------
    // Start Express Server
    // -------------------------------------------------------------------------

    app.listen(PORT, "0.0.0.0", () => {
      console.log(`Server running on port ${PORT}`);
      console.log(`Client URL: ${CLIENT_URL}`);
    });

    // -------------------------------------------------------------------------
    // Start Automatic Booking Expiration
    // -------------------------------------------------------------------------

    startBookingExpirationJob();

    // -------------------------------------------------------------------------
    // Verify Email Service
    // -------------------------------------------------------------------------

    verifyEmailConnection();
  } catch (error) {
    console.error(
      "SERVER STARTUP ERROR:",
      error.message
    );

    process.exit(1);
  }
};

// -----------------------------------------------------------------------------
// Start Application
// -----------------------------------------------------------------------------

startServer();